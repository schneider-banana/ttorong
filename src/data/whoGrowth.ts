/** 표시할 백분위와 대응 z-score */
export const PERCENTILE_Z: { p: number; z: number }[] = [
  { p: 3, z: -1.8808 },
  { p: 15, z: -1.0364 },
  { p: 50, z: 0 },
  { p: 85, z: 1.0364 },
  { p: 97, z: 1.8808 },
];

/** LMS + z-score → 측정값 (Box-Cox 역변환) */
export function valueAtZ(l: number, m: number, s: number, z: number): number {
  if (l === 0) return m * Math.exp(s * z);
  const base = 1 + l * s * z;
  return base > 0 ? m * Math.pow(base, 1 / l) : m;
}

/** 월별 백분위 곡선 (25개 월령 × 5개 백분위) */
export interface PercentilePoint {
  month: number;
  /** [P3, P15, P50, P85, P97] 순서 */
  values: number[];
}

export function getPercentileCurves(
  indicator: WhoIndicator,
  sex: WhoSex
): PercentilePoint[] {
  return WHO_MONTHLY[indicator][sex].map(([month, l, m, s]) => ({
    month,
    values: PERCENTILE_Z.map(({ z }) => valueAtZ(l, m, s, z)),
  }));
}
